    cam = Image.new("RGB", (224, 224), color=(255, 69, 0))
    cam_path = str(tmp_path / "cam.jpg")
    cam.save(cam_path)

    pdf_bytes = report_service.generate_advisory_pdf(
        advisory=SAMPLE_ADVISORY,
        original_image_path=img_path,
        heatmap_image_path=cam_path,
    )

    assert len(pdf_bytes) > 4000
    assert pdf_bytes.startswith(b"%PDF-")


