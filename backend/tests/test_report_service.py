def test_generate_advisory_pdf_with_image(tmp_path):
    """Verifies that original leaf and heatmap images are embedded without errors."""
    from PIL import Image
    
    img = Image.new("RGB", (224, 224), color=(34, 139, 34))
    img_path = str(tmp_path / "leaf.jpg")
